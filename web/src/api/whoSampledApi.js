/**
 * Searches across the WhoSampled database by artist, song, or sample origin
 */
export function searchWhoSampled(query) {
  if (!query || query.trim().length === 0) return WHO_SAMPLED_DATABASE;
  const q = query.toLowerCase().trim();

  return WHO_SAMPLED_DATABASE.filter(entry => {
    return entry.artist.toLowerCase().includes(q) ||
           entry.title.toLowerCase().includes(q) ||
           entry.sampleArtist.toLowerCase().includes(q) ||
           entry.sampleTitle.toLowerCase().includes(q) ||
           entry.genre.toLowerCase().includes(q) ||
           entry.type.toLowerCase().includes(q);
  });
}

