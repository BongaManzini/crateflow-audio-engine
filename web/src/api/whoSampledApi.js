/**
 * Parses a WhoSampled URL if pasted by the user
 * e.g. https://www.whosampled.com/Kanye-West/Through-the-Wire/
 */
export function parseWhoSampledUrl(url) {
  if (!url || typeof url !== 'string') return null;
  const clean = url.trim();

  const match = clean.match(/whosampled\.com\/([^\/]+)\/([^\/]+)/i);
  if (match) {
    const artist = decodeURIComponent(match[1]).replace(/-/g, ' ');
    const title = decodeURIComponent(match[2]).replace(/-/g, ' ');
    return {
      isValid: true,
      artist,
      title
    };
  }
  return null;
}
